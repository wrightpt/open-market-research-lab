const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {chromium} = require('playwright');
const TARGET = process.env.ORC_TEST_URL || 'http://127.0.0.1:8788/commons/';
const run = `browser-${Date.now()}`;
const output = path.join(process.cwd(), 'artifacts', run);
fs.mkdirSync(output, {recursive: true});

(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
  const errors = [], external = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith(new URL(TARGET).origin)) external.push(request.url()); });
  const check = name => { checks.push(name); console.log('PASS', name); };
  const noOverflow = async name => {
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), name);
    check(name);
  };
  try {
    await page.goto(TARGET);
    await page.waitForLoadState('networkidle');
    assert(await page.locator('.study-row').count() >= 2);
    await page.screenshot({path: path.join(output, 'register-desktop.png'), fullPage: true});
    check('seeded matched and disputed examples render');
    await noOverflow('desktop register fits viewport');
    await page.getByLabel('Search studies').fill('nothing-could-match-this');
    assert.match(await page.locator('#study-list').innerText(), /No studies match/);
    await page.getByLabel('Search studies').fill('');
    await page.locator('#filter').selectOption('disputed');
    assert(await page.locator('.study-row').count() >= 1);
    await page.locator('#filter').selectOption('all');
    check('search, empty state and status filter');

    await page.getByRole('link', {name: /New study/}).click();
    await page.locator('#new-view').waitFor({state: 'visible'});
    await page.getByLabel('Study title', {exact: true}).fill(`Cost accounting · ${run}`);
    await page.getByLabel('Hypothesis', {exact: true}).fill('Synthetic next-open accounting should preserve fees and causality. Literal <img src=x onerror=alert(1)> is untrusted text.');
    await page.getByRole('button', {name: /Save study/}).click();
    await page.waitForURL('**/#study/*');
    await page.locator('#study-view').waitFor({state: 'visible'});
    const originalUrl = page.url();
    assert.equal(await page.locator('#study-detail img').count(), 0);
    check('study creation and literal untrusted content rendering');
    await page.getByRole('button', {name: /Run development experiment/}).click();
    await page.getByRole('link', {name: /Export evidence/}).waitFor();
    assert.match(await page.locator('#study-detail').innerText(), /Awaiting replay/i);
    await page.locator('#persona').selectOption('reviewer');
    await page.getByRole('button', {name: /Replay & compare/}).click();
    await page.locator('#review-form').waitFor();
    assert.match(await page.locator('#study-detail').innerText(), /Complete match/);
    await page.getByLabel('Reasoning', {exact: true}).fill('The full report reproduces the synthetic accounting and retains the explicit limitations.');
    await page.getByRole('button', {name: /Record review/}).click();
    await page.waitForFunction(() => document.querySelectorAll('.review').length === 1);
    check('run, persona separation, exact replay and accepted review');
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('link', {name: /Export evidence/}).click()]);
    await download.saveAs(path.join(output, 'evidence-package.json'));
    const packageData = JSON.parse(fs.readFileSync(path.join(output, 'evidence-package.json')));
    assert.equal(packageData.study.status, 'reproduced');
    assert.equal(packageData.study.reviews[0].verdict, 'accepted');
    assert.equal(packageData.evidence_level, 'synthetic_engineering_only');
    await page.screenshot({path: path.join(output, 'study-desktop.png'), fullPage: true});
    await page.reload();
    await page.locator('#review-form').waitFor();
    assert.match(await page.locator('.review').innerText(), /full report reproduces/);
    check('portable evidence export and reload persistence');

    await page.getByRole('button', {name: /Fork a revision/}).click();
    await page.locator('#new-view').waitFor({state: 'visible'});
    await page.getByLabel('Study title', {exact: true}).fill(`Disputed import · ${run}`);
    await page.getByRole('button', {name: /Save study/}).click();
    await page.waitForURL('**/#study/*');
    await page.getByRole('link', {name: /Download submission/}).waitFor();
    const [submissionDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('link', {name: /Download submission/}).click()]);
    const submissionPath = path.join(output, 'submission.json');
    await submissionDownload.saveAs(submissionPath);
    const reportPath = path.join(output, 'development-report.json');
    execFileSync('python3', ['-m', 'market_lab', 'backtest', path.relative(process.cwd(), submissionPath), '--output', path.relative(process.cwd(), reportPath)], {cwd: process.cwd()});
    const altered = JSON.parse(fs.readFileSync(reportPath));
    altered.summary.fees_paid += 1;
    const alteredPath = path.join(output, 'altered-report.json');
    fs.writeFileSync(alteredPath, JSON.stringify(altered));
    await page.getByLabel('Attach benchmark report').setInputFiles(alteredPath);
    await page.getByRole('link', {name: /Export evidence/}).waitFor();
    await page.locator('#persona').selectOption('researcher');
    await page.getByRole('button', {name: /Replay & compare/}).click();
    await page.getByRole('heading', {name: 'This report did not reproduce.'}).waitFor();
    assert(await page.locator('#verdict option[value=accepted]').isDisabled());
    await page.locator('#verdict').selectOption('rejected');
    await page.getByLabel('Reasoning', {exact: true}).fill('The uploaded fee metric disagrees with deterministic replay. Both reports must remain retained.');
    await page.getByRole('button', {name: /Record review/}).click();
    await page.waitForFunction(() => document.querySelectorAll('.review').length === 1);
    check('linked fork, actual CLI report import, mismatch and rejected review');
    await page.setViewportSize({width: 390, height: 844});
    await noOverflow('mobile study fits viewport');
    await page.screenshot({path: path.join(output, 'study-mobile.png'), fullPage: true});
    await page.getByRole('link', {name: /Research register/}).first().click();
    await page.locator('#studies-view').waitFor({state: 'visible'});
    await noOverflow('mobile register fits viewport');
    await page.screenshot({path: path.join(output, 'register-mobile.png'), fullPage: true});
    await page.getByRole('link', {name: /Dataset & method/}).click();
    await page.locator('#dataset-view').waitFor({state: 'visible'});
    await noOverflow('mobile dataset fits viewport');
    await page.getByRole('link', {name: /Field guide/}).click();
    await page.locator('#guide-view').waitFor({state: 'visible'});
    await noOverflow('mobile guide fits viewport');
    await page.route('**/commons/api/studies', route => route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({error: {message: 'Simulated offline workspace.'}})}));
    await page.getByRole('link', {name: /Research register/}).first().click();
    await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('Simulated offline'));
    await page.unroute('**/commons/api/studies');
    await page.goto(originalUrl);
    await page.locator('#study-view').waitFor({state: 'visible'});
    check('server failure is visible and reload recovers');
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    check('no browser exceptions or external network requests');
    fs.writeFileSync(path.join(output, 'receipt.json'), JSON.stringify({status: 'passed', checks, errors, external, originalUrl, output}, null, 2));
    console.log(JSON.stringify({status: 'passed', checks: checks.length, output}));
  } catch (error) {
    await page.screenshot({path: path.join(output, 'failed.png'), fullPage: true});
    fs.writeFileSync(path.join(output, 'failed.json'), JSON.stringify({error: String(error), checks, errors, output}, null, 2));
    console.error(error); console.error('Evidence:', output); process.exitCode = 1;
  } finally { await browser.close(); }
})();
